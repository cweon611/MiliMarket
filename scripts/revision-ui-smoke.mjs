 const search=page.getByRole('textbox',{name:'식재료 검색',exact:true})
 await search.fill('바나나우유')
 await page.waitForFunction(()=>document.querySelectorAll('.category-row').length<14)
 const categories=await page.locator('.category-row').allTextContents()
 const total=Number((await page.locator('.results-heading h2 span').innerText()).replaceAll(',',''))
